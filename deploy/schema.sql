CREATE OR REPLACE FUNCTION settle_discretionary_paper_trades(entries JSONB)
RETURNS INTEGER LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(hashtext('discretionary_paper_settlement'));
    IF jsonb_typeof(entries) <> 'object' THEN RAISE EXCEPTION 'Invalid settlement batch'; END IF;
    IF EXISTS (
        SELECT 1 FROM jsonb_each(entries) e JOIN discretionary_paper_settlement s ON s.trade_id=e.key::numeric
        WHERE s.account_id<>(e.value->>'account_id')::bigint OR s.pnl<>(e.value->>'pnl')::numeric OR s.signal_id<>coalesce((e.value->>'signal_id')::bigint,0)
    ) THEN RAISE EXCEPTION 'Conflicting paper settlement'; END IF;
    INSERT INTO discretionary_paper_settlement(trade_id,signal_id,account_id,pnl)
    SELECT e.key::numeric,coalesce((e.value->>'signal_id')::bigint,0),(e.value->>'account_id')::bigint,(e.value->>'pnl')::numeric
    FROM jsonb_each(entries) e JOIN account a ON a.account_id=(e.value->>'account_id')::bigint
    WHERE a.account_type='paper'
    ON CONFLICT(trade_id) DO NOTHING;
    IF EXISTS (SELECT 1 FROM jsonb_each(entries) e
        LEFT JOIN discretionary_paper_settlement s ON s.trade_id=e.key::numeric WHERE s.trade_id IS NULL)
    THEN RAISE EXCEPTION 'Settlement account is not paper or not configured'; END IF;
    RETURN 1;
END $$;

CREATE OR REPLACE FUNCTION preserve_discretionary_account_route()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF (NEW.account_type,NEW.exchange_name,NEW.market_type) IS DISTINCT FROM
       (OLD.account_type,OLD.exchange_name,OLD.market_type)
       AND EXISTS (SELECT 1 FROM discretionary_account WHERE account_id=OLD.account_id)
    THEN RAISE EXCEPTION 'Discretionary account execution mode and venue are immutable'; END IF;
    RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS discretionary_account_route ON account;
CREATE TRIGGER discretionary_account_route BEFORE UPDATE OF account_type,exchange_name,market_type ON account
    FOR EACH ROW EXECUTE FUNCTION preserve_discretionary_account_route();
